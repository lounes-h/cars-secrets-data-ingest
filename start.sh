#!/usr/bin/env bash
# One command to run the whole pipeline: database, migrations, worker, API and dashboard.
#   ./start.sh          build and start (in the background)
#   ./start.sh --logs   same, then follow the logs
set -euo pipefail
cd "$(dirname "$0")"

die() { echo "error: $*" >&2; exit 1; }
command -v docker >/dev/null || die "Docker is not installed (https://docs.docker.com/get-docker/)"
docker info >/dev/null 2>&1 || die "Docker is not running"
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required"

if [ ! -f .env ]; then
  secret() { openssl rand -hex "$1"; }
  cat > .env <<ENV
# Generated by start.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Never commit this file.
POSTGRES_PASSWORD=$(secret 16)
DASHBOARD_USERNAME=admin
DASHBOARD_PASSWORD=$(secret 9)
SESSION_SECRET=$(secret 32)
HOST_UID=$(id -u)
HOST_GID=$(id -g)
DASHBOARD_PORT=8080
POSTGRES_PORT=5433
ENABLED_PROVIDERS=copart
STALE_AFTER_MINUTES=75
ARCHIVE_RETENTION_DAYS=7
COOKIE_SECURE=false
ENV
  chmod 600 .env
  echo "Created .env with generated credentials."
fi

set -a; . ./.env; set +a
mkdir -p data/inbox/copart data/archive data/failed

docker compose up --build --detach --wait

cat <<MSG

  Pipeline is running.

  Dashboard   http://localhost:${DASHBOARD_PORT:-8080}
  Login       ${DASHBOARD_USERNAME:-admin} / ${DASHBOARD_PASSWORD}   (stored in .env)
  Inbox       $(pwd)/data/inbox/copart/   <- save Copart CSV exports here

  Try it:     cp ~/Downloads/salesdata.csv data/inbox/copart/
              python3 scripts/simulate_export.py      # a realistic "next hour" export
  Logs:       docker compose logs -f worker api
  Stop:       docker compose down

MSG

if [ "${1:-}" = "--logs" ]; then
  docker compose logs -f worker api
fi
